import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const { HOSTED_BASE_PATH, ADMIN_BASE_PATH } = require('../src/http/constants.js');
const { MIME_TYPES } = require('../src/http/assets.js');
const ADMIN_ONLY = new Set(['admin.html', 'admin.js']);

const root = path.resolve(import.meta.dirname, '..');
const publicDir = path.join(root, 'public');
const target = path.join(root, 'worker', 'assets.generated.mjs');
const files = {};

for (const relative of walk(publicDir)) {
  const absolute = path.join(publicDir, relative);
  const normalized = relative.split(path.sep).join('/');
  const extension = path.extname(relative).toLowerCase();
  const file = { body: readFileSync(absolute, 'utf8'), type: MIME_TYPES[extension] || 'application/octet-stream' };
  if (ADMIN_ONLY.has(normalized)) files[`${ADMIN_BASE_PATH}/${normalized}`] = file;
  else files[`${HOSTED_BASE_PATH}/${normalized}`] = file;
  if (normalized === 'styles.css') files[`${ADMIN_BASE_PATH}/styles.css`] = file;
}

const source = `// Generated by scripts/embed-assets.mjs. Do not edit.\nconst FILES = ${JSON.stringify(files)};\nexport default FILES;\n`;
writeFileSync(target, source);
console.log(`Embedded ${Object.keys(files).length} KartBoard assets.`);

function walk(directory) {
  const entries = [];
  for (const name of readdirSync(directory)) {
    const absolute = path.join(directory, name);
    if (statSync(absolute).isDirectory()) entries.push(...walk(absolute).map(child => path.join(name, child)));
    else entries.push(name);
  }
  return entries;
}
